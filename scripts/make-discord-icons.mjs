// The icons the Discord bot uses, as gradient pictures: public/discord/icons/<name>.png (128 px, transparent), filled with the logo's gradient.
//   node scripts/make-discord-icons.mjs
// Line icons come from public/discord/icons/<name>.svg (drawn on a 24 px grid with currentColor strokes) or, for the newer ones, from Lucide (the same icon set the
// site uses); the brand marks come from public/brands. The colours are LOGO_STOPS from lib/logo-gradient.ts, so the icons, the logo and the background match.
// The same PNGs are uploaded to Discord as the bot's own emoji (owner dashboard, Discord page, "Upload the gradient icons"), which is how they show up inside
// titles and on buttons; as embed icons they are used straight from the site.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const pnpm = join(ROOT, 'node_modules', '.pnpm')
const sharpDir = readdirSync(pnpm).find((d) => d.startsWith('sharp@'))
const sharp = require(join(pnpm, sharpDir, 'node_modules', 'sharp'))
const lucideDir = join(pnpm, readdirSync(pnpm).find((d) => d.startsWith('lucide-react@')), 'node_modules', 'lucide-react', 'dist', 'esm', 'icons')

const stops = [...readFileSync(join(ROOT, 'lib', 'logo-gradient.ts'), 'utf8').matchAll(/\[([\d.]+), '(#[0-9a-fA-F]{6})'\]/g)].map((m) => [m[1], m[2]])
const defs = `<defs><linearGradient id="g" gradientUnits="userSpaceOnUse" x1="1" y1="2" x2="23" y2="22">${stops.map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join('')}</linearGradient></defs>`

const ICONS = join(ROOT, 'public', 'discord', 'icons')
// new line icons, by our name: the Lucide icon each one is
const LUCIDE = {
  verified: 'badge-check',
  founder: 'award',
  arrow: 'arrow-up-right',
  globe: 'globe',
  key: 'key-round',
  hand: 'hand',
  calendar: 'calendar-days',
  hash: 'hash',
  sparkles: 'sparkles',
  door: 'door-open',
  crown: 'crown',
  paypal: 'credit-card',
  tag: 'tag',
  video: 'clapperboard',
  music: 'music',
  megaphone: 'megaphone',
  scroll: 'scroll-text',
}
// brand marks (filled shapes), by our name: the file in public/brands
const BRANDS = { discord: 'discord', tiktok: 'tiktok', youtube: 'youtube', instagram: 'instagram', x: 'x' }

const attrs = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}="${v}"`).join(' ')
const node = ([tag, a]) => `<${tag} ${attrs(a)}/>`

const line = (inner) => `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 24 24" fill="none" stroke="url(#g)" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">${defs}${inner}</svg>`
const solid = (inner) => `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 24 24" fill="url(#g)">${defs}${inner}</svg>`

const made = []
async function png(name, svg) {
  const buf = await sharp(Buffer.from(svg), { density: 96 }).resize(128, 128, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png({ compressionLevel: 9 }).toBuffer()
  writeFileSync(join(ICONS, `${name}.png`), buf)
  made.push(name)
}

// 1) the existing icons: their SVG source, stroked with the gradient instead of white
for (const f of readdirSync(ICONS).filter((x) => x.endsWith('.svg'))) {
  const name = f.slice(0, -4)
  if (LUCIDE[name] || BRANDS[name]) continue // handled below (a source file of the same name is ignored)
  const src = readFileSync(join(ICONS, f), 'utf8')
  const inner = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replaceAll('currentColor', 'url(#g)')
  await png(name, line(inner))
}

// 2) the new line icons, from Lucide
for (const [name, lucide] of Object.entries(LUCIDE)) {
  const file = join(lucideDir, `${lucide}.mjs`)
  if (!existsSync(file)) throw new Error(`Lucide has no ${lucide}`)
  const { __iconNode } = await import(pathToFileURL(file).href)
  await png(name, line(__iconNode.map(node).join('')))
}

// 3) the brand marks, filled
for (const [name, brand] of Object.entries(BRANDS)) {
  const src = readFileSync(join(ROOT, 'public', 'brands', `${brand}.svg`), 'utf8')
  const paths = [...src.matchAll(/<path[^>]*\sd="([^"]+)"[^>]*\/?>/g)].map((m) => `<path d="${m[1]}"/>`).join('')
  await png(name, solid(paths))
}

writeFileSync(join(ROOT, 'lib', 'discord', 'icon-names.ts'), `// Generated by scripts/make-discord-icons.mjs. Do not edit by hand.\n/** Every gradient icon in public/discord/icons (a PNG each), and the emoji the bot owns on Discord under the same names (prefixed lg_). */\nexport const ICON_NAMES = ${JSON.stringify([...made].sort())} as const\nexport type IconName = (typeof ICON_NAMES)[number]\n`)
console.log(`${made.length} icons: ${made.sort().join(' ')}`)
